#!/usr/bin/env node
/**
 * Generate `src-tauri/Info.ios.plist`, which Tauri v2 auto-merges into the iOS app's `Info.plist`
 * at `tauri ios dev|build` time (additive for new keys; no config wiring needed).
 *
 * It adds a couple of things the generated project doesn't have:
 * - `UIBackgroundModes: [audio, fetch]` — `audio` lets discovery preview playback continue in the
 *   background (#79); `fetch` enables opportunistic background cloud sync via `BGAppRefreshTask` (#61).
 * - `BGTaskSchedulerPermittedIdentifiers: [audio.bbx.crate.sync.refresh]` — the background-sync task
 *   identifier must be declared here or `BGTaskScheduler` registration/submission throws at runtime.
 *   MUST match `TASK_IDENTIFIER` in `src-tauri/src/services/cloud_sync/background/ios.rs`.
 *
 * It deliberately does NOT register the Google OAuth callback URL scheme (the reversed client id).
 * Native cloud sign-in (#133) uses `ASWebAuthenticationSession` (via `tauri-plugin-web-auth`), which
 * intercepts its `callbackURLScheme` internally — it does not need, and actively conflicts with, a
 * `CFBundleURLTypes` registration for the same scheme. When the scheme is claimed in `Info.plist`,
 * iOS routes the OAuth redirect to the app's URL-open path instead of the in-flight auth session, so
 * the session's completion handler never fires and sign-in hangs on "Signing in…" forever. Leaving
 * the scheme unregistered lets the auth session own the callback. (Android is different: Custom Tabs
 * *do* need the scheme in `AndroidManifest.xml`, which is why it stays registered there.)
 *
 * `src-tauri/gen/apple` is gitignored (regenerated by `cargo tauri ios init`), so editing the
 * generated plist wouldn't persist — this merge file is the supported mechanism.
 *
 * The output is itself gitignored (kept out of git alongside `cloud_sync.config.json`). It is fully
 * derived, so it's overwritten on every run.
 *
 * Usage: node scripts/write-ios-plist.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = resolve(repoRoot, 'src-tauri/Info.ios.plist')

const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>UIBackgroundModes</key>
	<array>
		<string>audio</string>
		<string>fetch</string>
	</array>
	<key>BGTaskSchedulerPermittedIdentifiers</key>
	<array>
		<string>audio.bbx.crate.sync.refresh</string>
	</array>
</dict>
</plist>
`

writeFileSync(outPath, plist)

console.log(
	`[write-ios-plist] wrote ${outPath} (UIBackgroundModes: audio, fetch; BGTaskSchedulerPermittedIdentifiers: audio.bbx.crate.sync.refresh)`
)
