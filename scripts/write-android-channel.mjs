#!/usr/bin/env node
/**
 * Set the Android app's channel identity in `src-tauri/gen/android/app/channel.properties` for the
 * given release channel, so each channel ships a distinct installable that matches its Firebase
 * app / OAuth client / Play Integrity registration:
 *   dev     -> com.bbx_audio.crate.dev      ("Crate Dev")     — local `yarn dev:android` only
 *   staging -> com.bbx_audio.crate.staging  ("Crate Staging") — sideload
 *   prod    -> com.bbx_audio.crate.prod     ("Crate")         — release
 *
 * Why a script (the Android analog of `write-ios-bundle-id.mjs`): only the Gradle `applicationId`
 * varies per channel. The Tauri identifier stays `com.bbx-audio.crateapp` permanently — it is the
 * JNI anchor (tauri-build derives the `android_binding!` idents and the generated Kotlin package
 * from it, and the hand-written JNI symbols in Rust/Kotlin are literal against
 * `com.bbx_audio.crateapp`), so the per-channel Tauri configs must NOT reach `tauri android`.
 * `applicationId` ≠ `namespace` is standard Android; sandboxing, Firebase, and OAuth key off
 * `applicationId` while JNI/Kotlin stay on the fixed `namespace`. Every channel id is suffixed —
 * a last segment of `crate` is a Rust keyword and breaks the generated JNI binding.
 *
 * The properties file is gitignored; when absent, `app/build.gradle.kts` falls back to the same
 * dev defaults, so a fresh clone / bare Android Studio build is the dev channel.
 *
 * `oauthRedirectScheme` fills the manifest intent-filter for the Google OAuth redirect and MUST
 * equal `reversed_client_id(android_oauth_client_id)` (see cloud_sync/config.rs). It is derived
 * with the same precedence build.rs uses to bake the client id: env `GCLOUD_ANDROID_OAUTH_CLIENT_ID`
 * (CI secrets) first, else `android_oauth_client_id` from `src-tauri/cloud_sync.config.json`. If
 * neither is set a benign placeholder is written — cloud sync is unavailable, the build still works.
 *
 * Usage: node scripts/write-android-channel.mjs --channel <dev|staging|prod>
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const propertiesPath = resolve(repoRoot, 'src-tauri/gen/android/app/channel.properties')
const cloudConfigPath = resolve(repoRoot, 'src-tauri/cloud_sync.config.json')

const CHANNELS = {
	dev: { applicationId: 'com.bbx_audio.crate.dev', appName: 'Crate Dev' },
	staging: { applicationId: 'com.bbx_audio.crate.staging', appName: 'Crate Staging' },
	prod: { applicationId: 'com.bbx_audio.crate.prod', appName: 'Crate' },
}

const channelArgIndex = process.argv.indexOf('--channel')
const channel = channelArgIndex !== -1 ? process.argv[channelArgIndex + 1] : undefined
const target = channel && CHANNELS[channel]
if (!target) {
	console.error(
		`[write-android-channel] missing or invalid --channel (expected one of: ${Object.keys(CHANNELS).join(', ')})`,
	)
	process.exit(1)
}

// Same precedence as build.rs::bake_cloud_sync_config: explicit env (CI secrets) wins, then the
// local cloud_sync.config.json; missing config degrades (placeholder scheme), never breaks a build.
function androidOauthClientId() {
	const fromEnv = process.env.GCLOUD_ANDROID_OAUTH_CLIENT_ID?.trim()
	if (fromEnv) return fromEnv
	if (!existsSync(cloudConfigPath)) return undefined
	try {
		const config = JSON.parse(readFileSync(cloudConfigPath, 'utf8'))
		const fromFile = typeof config.android_oauth_client_id === 'string' ? config.android_oauth_client_id.trim() : ''
		return fromFile || undefined
	} catch (err) {
		console.warn(`[write-android-channel] could not parse ${cloudConfigPath}: ${err.message}`)
		return undefined
	}
}

// Mirrors cloud_sync/config.rs::reversed_client_id exactly.
function reversedClientId(clientId) {
	const head = clientId.endsWith('.apps.googleusercontent.com')
		? clientId.slice(0, -'.apps.googleusercontent.com'.length)
		: clientId
	return `com.googleusercontent.apps.${head}`
}

const clientId = androidOauthClientId()
const oauthRedirectScheme = clientId ? reversedClientId(clientId) : 'crate.oauth.unset'
if (!clientId) {
	console.warn(
		'[write-android-channel] no android_oauth_client_id configured (env or cloud_sync.config.json) — writing a placeholder OAuth scheme; cloud sync sign-in will be unavailable in this build',
	)
}

const contents = [
	'# Generated by scripts/write-android-channel.mjs — do not edit or commit (gitignored).',
	`channel=${channel}`,
	`applicationId=${target.applicationId}`,
	`appName=${target.appName}`,
	`oauthRedirectScheme=${oauthRedirectScheme}`,
	'',
].join('\n')

writeFileSync(propertiesPath, contents)
console.log(
	`[write-android-channel] set Android application id to ${target.applicationId} ("${target.appName}") for channel "${channel}"`,
)
